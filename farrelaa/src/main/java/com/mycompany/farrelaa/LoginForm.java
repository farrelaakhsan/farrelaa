    // Tombol Submit: validasi input, cek ke tabel pengguna di tk_db
    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String username = txtUsername.getText().trim();
        String password = new String(txtPassword.getPassword());

        // Validasi: tidak boleh kosong
        if (username.isEmpty() || password.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Username dan password wajib diisi!");
            return;
        }

        String sql = "SELECT * FROM pengguna WHERE username = ? AND password = ?";

        try (Connection conn = DriverManager.getConnection(DB_URL, DB_USER, DB_PASS);
             PreparedStatement ps = conn.prepareStatement(sql)) {

            ps.setString(1, username);
            ps.setString(2, password);

            try (ResultSet rs = ps.executeQuery()) {
                if (rs.next()) {
                    String role = rs.getString("role"); // pemilik / kasir
                    JOptionPane.showMessageDialog(this,
                            "Login berhasil! Selamat datang, " + username + " (" + role + ")");
                    // TODO: pindah ke Menu Utama (menunggu Main.java), kirim role
                } else {
                    JOptionPane.showMessageDialog(this, "Username atau password salah!");
                    txtPassword.setText("");
                    txtPassword.requestFocus();
                }
            }

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Koneksi database gagal: " + e.getMessage());
        }
    }//GEN-LAST:event_jButton1ActionPerformed

