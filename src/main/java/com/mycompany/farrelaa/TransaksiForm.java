    // Isi pilihan barang dari database lewat BarangDao (diambil dari Spring)
    private void muatBarang() {
        cmbBarang.removeAllItems();
        try {
            for (Barang b : AppContext.getBean(BarangDao.class).findAll()) {
                cmbBarang.addItem(b);
            }
        } catch (Exception e) {
            Util.error(this, e);
        }
    }

    private void tambahKeKeranjang() {
        Barang b = (Barang) cmbBarang.getSelectedItem();
        if (b == null) {
            Util.info(this, "Belum ada barang. Tambah dulu di Kelola Data Barang.");
            return;
        }
        int qty = (Integer) spnJumlah.getValue();

        // Cek apakah barang sudah ada di keranjang
        int baris = -1;
        int sudah = 0;
        for (int i = 0; i < model.getRowCount(); i++) {
            if (((Integer) model.getValueAt(i, 0)).equals(b.getId())) {
                baris = i;
                sudah = (Integer) model.getValueAt(i, 4);
            }
        }
        if (sudah + qty > b.getStok()) {
            Util.info(this, "Stok tidak cukup! Stok " + b.getNama() + ": " + b.getStok());
            return;
        }
        int jumlah = sudah + qty;
        long subtotal = b.getHarga() * jumlah;
        if (baris >= 0) {
            model.setValueAt(jumlah, baris, 4);
            model.setValueAt(subtotal, baris, 5);
        } else {
            model.addRow(new Object[]{b.getId(), b.getKode(), b.getNama(), b.getHarga(), jumlah, subtotal});
        }
        spnJumlah.setValue(1);
        hitungTotal();
    }

    private void hapusItem() {
        int baris = tabel.getSelectedRow();
        if (baris < 0) {
            Util.info(this, "Pilih item di keranjang dulu!");
            return;
        }
        model.removeRow(baris);
        hitungTotal();
    }

    private void kosongkan() {
        model.setRowCount(0);
        txtBayar.setText("");
        hitungTotal();
    }

    private long totalKeranjang() {
        long total = 0;
        for (int i = 0; i < model.getRowCount(); i++) {
            total += ((Number) model.getValueAt(i, 5)).longValue();
        }
        return total;
    }

    private void hitungTotal() {
        lblTotal.setText("Total: " + Util.rp(totalKeranjang()));
        hitungKembali();
    }

    private void hitungKembali() {
        long kembali;
        try {
            long bayar = Long.parseLong(txtBayar.getText().trim());
            kembali = Math.max(0, bayar - totalKeranjang());
        } catch (NumberFormatException e) {
            kembali = 0;
        }
        lblKembali.setText("Kembalian: " + Util.rp(kembali));
    }

    private void simpan() {
        if (model.getRowCount() == 0) {
            Util.info(this, "Keranjang masih kosong!");
            return;
        }
        long bayar;
        try {
            bayar = Long.parseLong(txtBayar.getText().trim());
        } catch (NumberFormatException e) {
            Util.info(this, "Isi uang bayar dengan angka!");
            return;
        }

        // Susun isi keranjang untuk dikirim ke DAO
        List<ItemKeranjang> items = new ArrayList<>();
        for (int i = 0; i < model.getRowCount(); i++) {
            ItemKeranjang item = new ItemKeranjang();
            item.setIdBarang((Integer) model.getValueAt(i, 0));
            item.setNama(String.valueOf(model.getValueAt(i, 2)));
            item.setJumlah((Integer) model.getValueAt(i, 4));
            items.add(item);
        }

        try {
            Transaksi t = AppContext.getBean(TransaksiDao.class).simpan(items, bayar);
            String ringkas = "Transaksi tersimpan.\nTotal: " + Util.rp(t.getTotal())
                    + "\nBayar: " + Util.rp(t.getBayar())
                    + "\nKembalian: " + Util.rp(t.getKembalian());
            int idTransaksi = t.getId();
            kosongkan();
            muatBarang();
            // Tawarkan cetak faktur (Jasper Report)
            int pilih = javax.swing.JOptionPane.showConfirmDialog(this, ringkas + "\n\nCetak faktur?",
                    "Transaksi", javax.swing.JOptionPane.YES_NO_OPTION);
            if (pilih == javax.swing.JOptionPane.YES_OPTION) {
                LaporanHelper.cetakFaktur(this, idTransaksi);
            }
        } catch (IllegalStateException e) {
            // stok atau uang bayar kurang (pesan dari DAO)
            Util.info(this, e.getMessage());
            muatBarang();
        } catch (Exception e) {
            Util.error(this, e);
        }
    }

