    // Baca dan cek tanggal Dari/Sampai untuk cetak laporan; null jika tidak valid
    private LocalDate[] bacaPeriode() {
        try {
            LocalDate dari = LocalDate.parse(txtDari.getText().trim());
            LocalDate sampai = LocalDate.parse(txtSampai.getText().trim());
            if (sampai.isBefore(dari)) {
                Util.info(this, "Tanggal 'Sampai' tidak boleh sebelum 'Dari'!");
                return null;
            }
            return new LocalDate[]{dari, sampai};
        } catch (DateTimeParseException e) {
            Util.info(this, "Format tanggal harus yyyy-MM-dd, contoh 2026-11-06");
            return null;
        }
    }

    private void tampilkan() {
        LocalDate dari;
        LocalDate sampai;
        try {
            dari = LocalDate.parse(txtDari.getText().trim());
            sampai = LocalDate.parse(txtSampai.getText().trim());
        } catch (DateTimeParseException e) {
            Util.info(this, "Format tanggal harus yyyy-MM-dd, contoh 2026-11-06");
            return;
        }
        if (sampai.isBefore(dari)) {
            Util.info(this, "Tanggal 'Sampai' tidak boleh sebelum 'Dari'!");
            return;
        }
        LocalDateTime a = dari.atStartOfDay();
        LocalDateTime b = sampai.plusDays(1).atStartOfDay();

        mJual.setRowCount(0);
        mStok.setRowCount(0);
        try {
            // DAO diambil dari Spring
            TransaksiDao transaksiDao = AppContext.getBean(TransaksiDao.class);
            BarangDao barangDao = AppContext.getBean(BarangDao.class);

            // Laporan penjualan
            List<Transaksi> list = transaksiDao.findByPeriode(a, b);
            long jumlah = 0;
            for (Transaksi t : list) {
                mJual.addRow(new Object[]{t.getId(), t.getTanggal().format(FMT),
                    Util.rp(t.getTotal()), Util.rp(t.getBayar()), Util.rp(t.getKembalian())});
                jumlah += t.getTotal();
            }
            lblTotal.setText("Total penjualan: " + Util.rp(jumlah) + " (" + list.size() + " transaksi)");

            // Laporan stok: stok sekarang + jumlah terjual pada periode
            Map<Integer, Long> terjual = transaksiDao.terjualPerBarang(a, b);
            for (Barang br : barangDao.findAll()) {
                mStok.addRow(new Object[]{br.getKode(), br.getNama(), br.getStok(),
                    terjual.getOrDefault(br.getId(), 0L)});
            }
        } catch (Exception e) {
            Util.error(this, e);
        }
    }

